def synth_gcode(layers, secs, bad_start=False):
    """Orca-style G-code (ElegooSlicer header), a short tube per layer. bad_start puts PrintDeck's current start
    block (M729 nozzle clean) in, to show what COSMOS does with it."""
    out = ["; generated by OrcaSlicer 2.3.1\n; estimated printing time (normal mode) = %dm %ds\n" % (secs // 60, secs % 60),
           "; total layer number: %d\n; filament_colour = #2F7DE1\n; filament_type = PLA\n" % layers,
           thumb_block(),
           "M140 S60\nG90\nM83\nG28\n" + ("M729 ;clean nozzle\n" if bad_start else "") + "M109 S210\n"]
    for i in range(layers):
        z = 0.2 + i * 0.2
        out.append(";LAYER_CHANGE\n;Z:%.2f\nSET_PRINT_STATS_INFO CURRENT_LAYER=%d\n;TYPE:Outer wall\n" % (z, i + 1))
        for k in range(37):
            a = k / 36 * 2 * math.pi
            out.append("G1 X%.3f Y%.3f Z%.2f E0.05\n" % (128 + 20 * math.cos(a), 128 + 20 * math.sin(a), z))
    out.append("M104 S0\nM140 S0\n")
    return "".join(out).encode()

def thumb_block():
    """An Orca-style embedded PNG thumbnail, so clients that read the G-code header find a picture."""
    if Image is None: return ""
    im = Image.new("RGB", (96, 96), (28, 30, 36)); d = ImageDraw.Draw(im)
    d.rectangle([28, 22, 68, 80], fill=(47, 125, 225)); d.ellipse([28, 14, 68, 30], fill=(80, 150, 240))
    b = io.BytesIO(); im.save(b, "PNG"); enc = base64.b64encode(b.getvalue()).decode()
    lines = "".join("; %s\n" % enc[i:i + 78] for i in range(0, len(enc), 78))
    return "; THUMBNAIL_BLOCK_START\n; thumbnail begin 96x96 %d\n%s; thumbnail end\n; THUMBNAIL_BLOCK_END\n" % (len(enc), lines)

FILES = {}   # path (relative to gcodes root) -> dict(data, modified)
