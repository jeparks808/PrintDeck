def query_objects(req):
    """req: {name: None | [fields]} -> {"eventtime", "status"}"""
    allobj = K.objects(); out = {}
    for name, fields in req.items():
        if name not in allobj: continue
        o = allobj[name]
        out[name] = {k: v for k, v in o.items() if not fields or k in fields}
    return {"eventtime": now() - T0, "status": out}

