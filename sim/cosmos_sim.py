#!/usr/bin/env python3
"""Virtual Centauri Carbon running OpenCentauri COSMOS (Klipper + Moonraker), for testing PrintDeck before the
real printer is reflashed.

What the real COSMOS printer exposes, and so what this serves (one port, default 17125; the printer uses 80):
  HTTP  Moonraker REST API     /server/*, /printer/*, /machine/*, /access/*
  WS    Moonraker JSON-RPC     /websocket  (printer.objects.subscribe -> notify_status_update, etc.)
  HTTP  webcam (mjpg-streamer) /webcam/?action=stream, /webcam/?action=snapshot
What it does NOT serve, like COSMOS: Elegoo SDCP (UDP 3000 discovery, ws :3030, MJPEG :3031, /local/ on :80).

Klipper object names follow a real COSMOS 26.10.1 + CANVAS printer (AFC 1.2.1: `AFC`, `AFC_lane CANVAS_1..4`,
`temperature_sensor chamber`, `led case`, `led hotend`). Names marked ASSUMED below were not seen on a real one;
clients should discover names from /printer/objects/list rather than hard-code them.

COSMOS behaviours modelled because they matter to PrintDeck:
  * M729 / M8213 / M8212 (Elegoo's nozzle-clean and light codes, which PrintDeck's slicer writes) put Klipper into
    an emergency shutdown, as the COSMOS docs warn. Unknown commands (e.g. Elegoo's M6211) answer
    `Unknown command`, as Klipper does.
  * SDCP JSON sent to /websocket gets a JSON-RPC "Invalid Request" error, which is what an unmodified PrintDeck
    pointed at port 80 would see.

  python3 -I sim/cosmos_sim.py [--port 17125] [--host 127.0.0.1] [--scenario idle|printing] [--speed 30]
Standard library + Pillow (camera frames).
"""
