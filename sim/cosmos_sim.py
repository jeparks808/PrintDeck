def file_meta(path):
    f = FILES.get(path)
    if not f: return None
    head = f["data"][:4096].decode("utf-8", "replace")
    m = re.search(r"total layer number: (\d+)", head); layers = int(m.group(1)) if m else None
    m = re.search(r"estimated printing time \(normal mode\) = (\d+)m (\d+)s", head)
    est = int(m.group(1)) * 60 + int(m.group(2)) if m else None
    m = re.search(r"generated by (.+)", head)
    return {"filename": path, "size": len(f["data"]), "modified": f["modified"], "uuid": hashlib.md5(path.encode()).hexdigest(),
            "slicer": (m.group(1).split()[0] if m else "Unknown"), "slicer_version": (m.group(1).split()[-1] if m else ""),
            "layer_count": layers, "estimated_time": est, "object_height": layers * 0.2 if layers else None,
            "first_layer_height": 0.2, "layer_height": 0.2, "filament_type": "PLA", "filament_colors": ["#2F7DE1"],
            "filament_total": 1234.5, "filament_weight_total": 3.7,
            "thumbnails": [{"width": 300, "height": 300, "size": 4000, "relative_path": ".thumbs/%s-300x300.png" % path.rsplit(".", 1)[0]}],
            "print_start_time": None, "job_id": None}

# ------------------------------------------------------------------------------------------- printer model ----
def mesh_matrix(nx=5, ny=5, tilt=0.0):
    return [[round(0.08 * math.exp(-(((gx / (nx - 1)) * 2 - 1) ** 2 + ((gy / (ny - 1)) * 2 - 1) ** 2) * 1.3) - 0.04
                   + tilt * (gy / (ny - 1) - 0.5), 4) for gx in range(nx)] for gy in range(ny)]

class Klipper:
    def __init__(self):
        self.state, self.state_message = "ready", "Printer is ready"
        self.pos = [128.0, 128.0, 10.0, 0.0]; self.homed = ""; self.relative = False
        self.ext = {"temperature": 24.0, "target": 0.0, "power": 0.0}
        self.bed = {"temperature": 23.5, "target": 0.0, "power": 0.0}
        self.chamber = 25.0
        self.fans = {"fan": 0.0, "fan_generic aux_fan": 0.0, "fan_generic chamber_fan": 0.0}   # ASSUMED generic names
        self.leds = {"case": [0, 0, 0, 1.0], "hotend": [0, 0, 0, 0.0]}
        self.speed_factor, self.extrude_factor = 1.0, 1.0
        self.z_offset = 0.0
        self.steppers = {"stepper_x": False, "stepper_y": False, "stepper_z": False, "extruder": False}
        self.mesh = mesh_matrix(tilt=-0.15); self.mesh_profile = "default"
        self.lanes = {
            "CANVAS_1": {"map": "T0", "material": "PLA", "color": "#1A1A1A", "filament_name": "", "weight": 1000, "prep": True, "load": True},
            "CANVAS_2": {"map": "T1", "material": "PLA", "color": "#F2C200", "filament_name": "", "weight": 820, "prep": True, "load": True},
            "CANVAS_3": {"map": "T2", "material": "PLA", "color": "#D32F2F", "filament_name": "", "weight": 640, "prep": True, "load": True},
            "CANVAS_4": {"map": "T3", "material": "PLA", "color": "#2E9E44", "filament_name": "", "weight": 300, "prep": True, "load": False},
        }
        self.current_lane = "CANVAS_1"
        self.job = None        # dict(file, start, elapsed, layers, est, lines)
        self.print_state, self.print_message = "standby", ""
        self.history = []
        self.gcode_store = []
        self.temp_store = {k: {"temperatures": [], "targets": []} for k in ("extruder", "heater_bed", "temperature_sensor chamber")}
        self.last_tick = now(); self.last_store = 0

    # --- G-code ------------------------------------------------------------------------------------------
    def respond(self, msg, kind="response"):
        self.gcode_store.append({"message": msg, "time": now(), "type": kind}); self.gcode_store = self.gcode_store[-200:]
        NOTIFY.append({"jsonrpc": "2.0", "method": "notify_gcode_response", "params": [msg]})

    def shutdown(self, why):
        self.state, self.state_message = "shutdown", why
        for h in (self.ext, self.bed): h["target"] = 0.0
        if self.job: self.end_job("error", why)
        self.respond("!! " + why, "response")
        NOTIFY.append({"jsonrpc": "2.0", "method": "notify_klippy_shutdown"})
        log("KLIPPER SHUTDOWN: " + why)

    def run_script(self, script):
        """Run a G-code script. Returns None on success or an error string (Klipper's gcode error)."""
        for raw in script.splitlines():
            line = raw.split(";", 1)[0].strip()
            if not line: continue
            self.respond(line, "command")
            if self.state == "shutdown" and line.upper() not in ("FIRMWARE_RESTART", "RESTART"):
                return "Printer is shutdown"
            err = self.gcode(line)
            if err: self.respond("!! " + err, "response"); return err
        return None

    def gcode(self, line):
        parts = line.split(); cmd = parts[0].upper()
        args = {}
        for p in parts[1:]:
            if "=" in p: k, v = p.split("=", 1); args[k.upper()] = v
            elif p[:1].isalpha(): args[p[0].upper()] = p[1:]
        num = lambda k, d=None: float(args[k]) if k in args and args[k] != "" else d
        if cmd in ("M729", "M8213", "M8212"):
            self.shutdown("Elegoo-only command %s is not supported by COSMOS (emergency stop). Remove it from the slicer's start/end G-code." % cmd)
            return "Printer is shutdown"
        if cmd in ("FIRMWARE_RESTART", "RESTART"):
            self.state, self.state_message = "ready", "Printer is ready"; NOTIFY.append({"jsonrpc": "2.0", "method": "notify_klippy_ready"}); return None
        if cmd in ("M104", "M109"):
            self.ext["target"] = num("S", 0); return None
        if cmd in ("M140", "M190"):
            self.bed["target"] = num("S", 0); return None
        if cmd == "SET_HEATER_TEMPERATURE":
            h = {"extruder": self.ext, "heater_bed": self.bed}.get(args.get("HEATER", "").lower())
            if h is None: return "Unknown heater '%s'" % args.get("HEATER")
            h["target"] = num("TARGET", 0); return None
        if cmd == "M106":
            self.fans["fan"] = max(0, min(1, num("S", 255) / 255)); return None
        if cmd == "M107":
            self.fans["fan"] = 0.0; return None
        if cmd == "SET_FAN_SPEED":
            k = "fan_generic " + args.get("FAN", "")
            if k not in self.fans: return "Unknown fan '%s'" % args.get("FAN")
            self.fans[k] = max(0, min(1, num("SPEED", 0))); return None
        if cmd == "M220":
            self.speed_factor = num("S", 100) / 100; return None
        if cmd == "M221":
            self.extrude_factor = num("S", 100) / 100; return None
        if cmd == "SET_LED":
            name = args.get("LED", "")
            if name not in self.leds: return "Unknown LED '%s'" % name
            self.leds[name] = [num("RED", 0), num("GREEN", 0), num("BLUE", 0), num("WHITE", 0)]; return None
        if cmd == "G28":
            axes = [a for a in "XYZ" if a in [p.upper() for p in parts[1:]]] or list("XYZ")
            for a in axes:
                self.pos["XYZ".index(a)] = 0.0
                if a.lower() not in self.homed: self.homed += a.lower()
                self.steppers["stepper_" + a.lower()] = True
            self.homed = "".join(sorted(self.homed, key="xyz".index)); return None
        if cmd == "G90": self.relative = False; return None
        if cmd == "G91": self.relative = True; return None
        if cmd in ("G0", "G1"):
            for i, a in enumerate("XYZ"):
                if a in args:
                    if a.lower() not in self.homed: return "Must home axis first: %.3f %.3f %.3f [0.000]" % tuple(self.pos[:3])
                    v = float(args[a]); self.pos[i] = self.pos[i] + v if self.relative else v
                    lim = (0, 256)
                    if not lim[0] - 2 <= self.pos[i] <= lim[1] + 2:
                        self.pos[i] -= v if self.relative else 0
                        return "Move out of range: %.3f %.3f %.3f [0.000]" % tuple(self.pos[:3])
            if "E" in args: self.pos[3] += float(args["E"])
            return None
        if cmd in ("M84", "M18"):
            for k in self.steppers: self.steppers[k] = False
            self.homed = ""; return None
        if cmd == "SET_GCODE_OFFSET":
            if "Z_ADJUST" in args: self.z_offset += float(args["Z_ADJUST"])
            if "Z" in args: self.z_offset = float(args["Z"])
            return None
        if cmd == "BED_MESH_CALIBRATE":
            self.mesh = mesh_matrix(tilt=-0.1 + 0.02 * (len(self.history) % 3)); self.mesh_profile = args.get("PROFILE", "default"); return None
        if cmd == "BED_MESH_PROFILE":
            if "LOAD" in args: self.mesh_profile = args["LOAD"]
            return None
        if cmd == "BED_MESH_CLEAR":
            self.mesh_profile = ""; return None
        if cmd in ("SET_COLOR", "SET_MATERIAL", "SET_WEIGHT", "SET_SPOOL_ID"):
            lane = self.lanes.get(args.get("LANE", ""))
            if lane is None: return "Unknown lane '%s'" % args.get("LANE")
            if cmd == "SET_COLOR":
                c = args.get("COLOR", "").lstrip("#")
                if not re.fullmatch(r"[0-9A-Fa-f]{6}", c): return "Invalid COLOR"
                lane["color"] = "#" + c.upper()
            elif cmd == "SET_MATERIAL": lane["material"] = args.get("MATERIAL", "")
            elif cmd == "SET_WEIGHT": lane["weight"] = num("WEIGHT", 0)
            return None
        if re.fullmatch(r"T[0-3]", cmd) or cmd == "CHANGE_TOOL":
            t = cmd if cmd != "CHANGE_TOOL" else args.get("LANE", "")
            for n, l in self.lanes.items():
                if l["map"] == t or n == t: self.current_lane = n
            return None
        if cmd in ("LOAD_FILAMENT", "UNLOAD_FILAMENT", "CHECK_CALIBRATION", "SET_PRINT_STATS_INFO", "M83", "M82", "M400",
                   "PRINT_START", "PRINT_END", "TURN_OFF_HEATERS"):
            if cmd == "TURN_OFF_HEATERS": self.ext["target"] = self.bed["target"] = 0.0
            if cmd == "SET_PRINT_STATS_INFO" and self.job and "CURRENT_LAYER" in args: self.job["layer"] = int(args["CURRENT_LAYER"])
            return None
        if cmd == "PAUSE": return self.pause()
        if cmd == "RESUME": return self.resume()
        if cmd == "CANCEL_PRINT": return self.cancel()
        if cmd == "SDCARD_PRINT_FILE": return self.start(args.get("FILENAME", "").strip('"'))
        self.respond('// Unknown command:"%s"' % cmd)   # Klipper reports and carries on
        return None

    # --- jobs --------------------------------------------------------------------------------------------
    def start(self, path):
        if self.state != "ready": return "Printer not ready"
        if self.job: return "Already printing"
        f = FILES.get(path)
        if not f: return "File not found: %s" % path
        meta = file_meta(path)
        self.job = {"file": path, "start": now(), "elapsed": 0.0, "layer": 0, "layers": meta["layer_count"] or 1,
                    "est": meta["estimated_time"] or 1800, "size": len(f["data"]), "paused": False}
        self.print_state, self.print_message = "printing", ""
        self.history.insert(0, {"job_id": "%06X" % (len(self.history) + 1), "filename": path, "status": "in_progress",
                                "start_time": now(), "end_time": None, "print_duration": 0.0, "total_duration": 0.0,
                                "filament_used": 0.0, "exists": True, "metadata": file_meta(path) or {}})
        log("print start: " + path)
        # Run the start block now (the part before the first layer), as Klipper would stream it.
        head = f["data"].split(b";LAYER_CHANGE", 1)[0].decode("utf-8", "replace")
        self.run_script("\n".join(l for l in head.splitlines() if not l.startswith(";")))   # a shutdown here ends the job
        return None

    def pause(self):
        if not self.job or self.print_state != "printing": return "Print not in progress"
        self.print_state = "paused"; return None

    def resume(self):
        if not self.job or self.print_state != "paused": return "Print is not paused, resume aborted"
        self.print_state = "printing"; return None

    def cancel(self):
        if not self.job: return "No print in progress"
        self.end_job("cancelled", ""); self.ext["target"] = self.bed["target"] = 0.0; return None

    def end_job(self, status, msg):
        j = self.job; self.job = None
        self.print_state, self.print_message = status, msg
        h = self.history[0] if self.history and self.history[0]["status"] == "in_progress" else None
        if h is None:
            h = {"job_id": "%06X" % (len(self.history) + 1), "filename": j["file"], "start_time": j["start"], "exists": True,
                 "metadata": file_meta(j["file"]) or {}}
            self.history.insert(0, h)
        h.update({"status": {"error": "klippy_shutdown"}.get(status, "completed" if status == "complete" else status),
                  "end_time": now(), "print_duration": j["elapsed"], "total_duration": now() - j["start"], "filament_used": j["elapsed"] * 0.4})
        log("print %s: %s" % (status, j["file"]))

    def tick(self):
        t = now(); dt = t - self.last_tick; self.last_tick = t
        for h, amb, rate in ((self.ext, 24.0, 6.0), (self.bed, 23.5, 1.2)):
            goal = h["target"] if h["target"] > 0 else amb
            h["temperature"] += max(-rate * dt, min(rate * dt, goal - h["temperature"])) + math.sin(t * 2.1) * 0.03
            h["power"] = 0.6 if h["target"] > h["temperature"] + 1 else (0.25 if h["target"] else 0.0)
        self.chamber += (25 + 0.15 * (self.bed["temperature"] - 23.5) - self.chamber) * min(1, dt / 30)
        j = self.job
        if j and self.print_state == "printing" and self.state == "ready":
            j["elapsed"] += dt * A.speed * self.speed_factor
            j["layer"] = min(j["layers"], 1 + int(j["layers"] * j["elapsed"] / j["est"]))
            if j["elapsed"] >= j["est"]: self.end_job("complete", "")
        if t - self.last_store >= 1:
            self.last_store = t
            for k, v in (("extruder", self.ext), ("heater_bed", self.bed), ("temperature_sensor chamber", {"temperature": self.chamber, "target": 0})):
                s = self.temp_store[k]; s["temperatures"] = (s["temperatures"] + [round(v["temperature"], 2)])[-1200:]
                if k != "temperature_sensor chamber": s["targets"] = (s["targets"] + [v["target"]])[-1200:]

    # --- Klipper objects ---------------------------------------------------------------------------------
