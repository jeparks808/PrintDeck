def http_response(writer, code, body, ctype="application/json", extra=b""):
    reason = {200: "OK", 201: "Created", 400: "Bad Request", 404: "Not Found", 405: "Method Not Allowed"}.get(code, "Error")
    writer.write(b"HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %d\r\nAccess-Control-Allow-Origin: *\r\nConnection: close\r\n%s\r\n"
                 % (code, reason.encode(), ctype.encode(), len(body), extra) + body)

def jbody(obj): return json.dumps(obj).encode()

def parse_multipart(ctype, data):
    m = re.search(r'boundary="?([^";]+)"?', ctype)
    if not m: return {}, None
    out, fileinfo = {}, None
    for part in data.split(b"--" + m.group(1).encode()):
        if b"\r\n\r\n" not in part: continue
        hdr, val = part.split(b"\r\n\r\n", 1); val = val[:-2] if val.endswith(b"\r\n") else val
        hd = hdr.decode("utf-8", "replace")
        n = re.search(r'name="([^"]*)"', hd); fn = re.search(r'filename="([^"]*)"', hd)
        if not n: continue
        if fn: fileinfo = (fn.group(1), val)
        else: out[n.group(1)] = val.decode("utf-8", "replace")
    return out, fileinfo

