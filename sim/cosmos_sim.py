def ws_frame(payload, op=1):
    n = len(payload)
    hdr = bytes([0x80 | op]) + (bytes([n]) if n < 126 else (b"\x7e" + struct.pack(">H", n) if n < 65536 else b"\x7f" + struct.pack(">Q", n)))
    return hdr + payload

async def ws_read(reader):
    b1, b2 = await reader.readexactly(2)
    op, n = b1 & 15, b2 & 127
    if n == 126: n = struct.unpack(">H", await reader.readexactly(2))[0]
    elif n == 127: n = struct.unpack(">Q", await reader.readexactly(8))[0]
    mask = await reader.readexactly(4) if b2 & 128 else b"\0\0\0\0"
    data = bytes(c ^ mask[i % 4] for i, c in enumerate(await reader.readexactly(n)))
    return op, data

async def ws_session(reader, writer, hdrs):
    acc = base64.b64encode(hashlib.sha1((hdrs.get("sec-websocket-key", "") + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode()).digest())
    writer.write(b"HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: " + acc + b"\r\n\r\n")
    await writer.drain()
    client = {"writer": writer, "subs": {}, "last": {}}
    WS_CLIENTS.add(id(client)); CLIENTS[id(client)] = client
    log("websocket client connected")
    try:
        while True:
            op, data = await ws_read(reader)
            if op == 8: break
            if op == 9: writer.write(ws_frame(data, 10)); continue
            if op != 1: continue
            try:
                msg = json.loads(data)
            except ValueError:
                writer.write(ws_frame(jbody({"jsonrpc": "2.0", "error": {"code": -32700, "message": "Parse error"}, "id": None}))); continue
            if not isinstance(msg, dict) or msg.get("jsonrpc") != "2.0" or "method" not in msg:
                log("websocket: not JSON-RPC (e.g. Elegoo SDCP): %s" % data[:120].decode("utf-8", "replace"))
                writer.write(ws_frame(jbody({"jsonrpc": "2.0", "error": {"code": -32600, "message": "Invalid Request"}, "id": None})))
                await writer.drain(); continue
            mid, meth, params = msg.get("id"), msg["method"], msg.get("params") or {}
            try:
                if meth == "printer.objects.subscribe":
                    client["subs"] = params.get("objects", {}); res = query_objects(client["subs"])
                    client["last"] = json.loads(json.dumps(res["status"]))
                elif meth == "server.connection.identify":
                    res = {"connection_id": id(client)}
                elif meth in RPC:
                    res = api("POST", RPC[meth], {}, params)
                else:
                    raise ApiError(-32601, "Method not found")
                writer.write(ws_frame(jbody({"jsonrpc": "2.0", "result": res, "id": mid})))
            except ApiError as e:
                writer.write(ws_frame(jbody({"jsonrpc": "2.0", "error": {"code": e.code, "message": e.msg}, "id": mid})))
            await writer.drain()
    except (asyncio.IncompleteReadError, ConnectionError):
        pass
    finally:
        WS_CLIENTS.discard(id(client)); CLIENTS.pop(id(client), None); log("websocket client gone")
        try: writer.close()
        except Exception: pass

CLIENTS = {}
async def ticker():
    while True:
        K.tick()
        notes, NOTIFY[:] = list(NOTIFY), []
        for c in list(CLIENTS.values()):
            try:
                for n in notes: c["writer"].write(ws_frame(jbody(n)))
                if c["subs"]:
                    cur = query_objects(c["subs"])["status"]; diff = {}
                    for name, o in cur.items():
                        d = {k: v for k, v in o.items() if c["last"].get(name, {}).get(k) != v}
                        if d: diff[name] = d
                    if diff:
                        c["last"] = json.loads(json.dumps(cur))
                        c["writer"].write(ws_frame(jbody({"jsonrpc": "2.0", "method": "notify_status_update", "params": [diff, now() - T0]})))
                await c["writer"].drain()
            except Exception:
                pass
        await asyncio.sleep(0.25)

async def main():
    srv = await asyncio.start_server(handle, A.host, A.port)
    log("virtual COSMOS printer (Moonraker API) on http://%s:%d  scenario=%s x%g  (no SDCP: nothing on UDP 3000 / 3030 / 3031)"
        % (A.host, A.port, A.scenario, A.speed))
    await asyncio.gather(srv.serve_forever(), ticker())

